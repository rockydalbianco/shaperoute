/**
 * Which exercises each stretching category has (TASK-520, ADR-0415), from
 * the list the user approved on 2026-11-27 (Annex B of the task file): every
 * exercise there says which categories it is good for, and this is that
 * table turned round. In a category the exercises that name it first come
 * first, then the others, each in the list's order; a routine takes them
 * from the top (`compose.ts`). Written by a script from the task file, not
 * by hand; `categories.test.ts` checks it against the exercises.
 *
 * A key is never changed: the last choice of a category is remembered by
 * it, and a session done is saved under it. So a key is letters, digits
 * and underscores, forty at most: what the server takes as a routine's
 * name (`ROUTINE_PATTERN` in stretch_sessions.py).
 */

